#!/usr/bin/env python3
"""Scrape + redeploy jav-report (Vercel project 'jav-report', prod URL https://jav-report.vercel.app).

Usage:
  python3 deploy.py            # scrape javtext /latest (PAGES env, default 3) then prepare deploy bundle
  python3 deploy.py --no-scrape
Steps:
 1. scrape.py -> data/items.json, public/data.json, public/covers/*.jpg (validated landscape R18/DMM jackets only)
    + favorites: data/favorites.json (config: slug,name,aliases,javtext_id) -> data/fav_items.json, public/fav.json
      (incremental; FAV_FULL=1 re-walks all actress pages; FAV=0 skips; ONLY_FAV=1 runs favorites only; FAV_SLUG=<slug> crawls just that actress).
      To add an actress: append to data/favorites.json, then run FAV_FULL=1 python3 deploy.py\n    Sample stills: fetch_samples() pulls official DMM {cid}jp-N.jpg into public/samples/{CODE}/ (never magnets/video).\n      Normal Wed/Fri scrape already fetches samples for new releases + refreshed fav works.\n      Backfill: SAMPLES_ONLY=1 SAMPLES_N=20 SAMPLES_FAV=8 python3 scrape.py  -> public/samples.json
 2. Build bundle in /workspace/jav-b64: <sha1>.b64 per file + manifest.json ([{file,sha,size}]),
    files = contents of public/ at root + vercel.json (noindex headers, cleanUrls; no build).
 3. Deploy:
    a) If VERCEL_TOKEN env is set: uploads via REST (POST /v2/files) and creates a production deployment (POST /v13/deployments).
    b) Otherwise (agent routine): use the Vercel MCP connector (namespace user-Vercel), NO teamId/slug param:
       - upload_file {contentLength:size, xVercelDigest:sha, requestBody:"$file:/workspace/jav-b64/<sha>.b64"} for each NEW sha
         (manifest_new.json lists only shas not uploaded before; uploading all is also fine)
       - create_deployment {skipAutoDetectionConfirmation:"1", requestBody:"$file:/workspace/jav-b64/deploy_body.json"}
         (deploy_body.json is generated by this script; equivalent to requestBody:{name:"jav-report",project:"jav-report",target:"production",
         projectSettings:{framework:null,buildCommand:null,outputDirectory:null,installCommand:null}, files: manifest.json}}
       - get_deployment until readyState READY; then curl -I https://jav-report.vercel.app
"""
import os,sys,json,hashlib,base64,subprocess,urllib.request
ROOT=os.path.dirname(os.path.abspath(__file__)); OUT="/workspace/jav-b64"
VJSON={"cleanUrls":True,"headers":[{"source":"/(.*)","headers":[{"key":"X-Robots-Tag","value":"noindex, nofollow"}]},{"source":"/covers/(.*)","headers":[{"key":"Cache-Control","value":"public, max-age=31536000, immutable"}]},{"source":"/thumbs/(.*)","headers":[{"key":"Cache-Control","value":"public, max-age=31536000, immutable"}]},{"source":"/samples/(.*)","headers":[{"key":"Cache-Control","value":"public, max-age=31536000, immutable"}]},{"source":"/data.json","headers":[{"key":"Cache-Control","value":"public, max-age=300"}]},{"source":"/fav.json","headers":[{"key":"Cache-Control","value":"public, max-age=300"}]},{"source":"/samples.json","headers":[{"key":"Cache-Control","value":"public, max-age=300"}]}]}
def bundle():
    os.makedirs(OUT,exist_ok=True); pub=os.path.join(ROOT,"public"); api=os.path.join(ROOT,"api")
    files=[(os.path.relpath(os.path.join(d,f),pub),open(os.path.join(d,f),"rb").read()) for d,_,fs in os.walk(pub) for f in fs if f!="vercel.json"]
    if os.path.isdir(api):
        for d,_,fs in os.walk(api):
            for f in fs:
                if not f.endswith('.js'): continue
                rel=os.path.join('api', os.path.relpath(os.path.join(d,f), api)).replace('\\','/')
                files.append((rel, open(os.path.join(d,f),'rb').read()))
    # vercel.json: static headers + serverless
    vj=dict(VJSON)
    vj["functions"]={ "api/**/*.js": { "memory": 256, "maxDuration": 30 } }
    files.append(("vercel.json",json.dumps(vj,separators=(",",":")).encode()))
    open(os.path.join(pub,"vercel.json"),"wb").write(files[-1][1])
    done_p=os.path.join(OUT,"uploaded.json"); done=set(json.load(open(done_p))) if os.path.exists(done_p) else set()
    man=[]
    for rel,b in files:
        s=hashlib.sha1(b).hexdigest(); open(f"{OUT}/{s}.b64","w").write(base64.b64encode(b).decode())
        man.append({"file":rel,"sha":s,"size":len(b)})
    json.dump(man,open(f"{OUT}/manifest.json","w"))
    body={"name":"jav-report","project":"jav-report","target":"production","files":man,
          "projectSettings":{"framework":None,"buildCommand":None,"outputDirectory":None,"installCommand":None}}
    open(f"{OUT}/deploy_body.json","w").write(json.dumps(body,separators=(",",":")))
    new=list({m["sha"]:m for m in man if m["sha"] not in done}.values())
    json.dump(new,open(f"{OUT}/manifest_new.json","w"))
    print(f"bundle: {len(man)} files, {len(new)} new shas -> {OUT}"); return man,files
def rest_deploy(man,files,tok):
    H={"Authorization":"Bearer "+tok}; data={hashlib.sha1(b).hexdigest():b for _,b in files}
    for m in {m["sha"]:m for m in man}.values():
        r=urllib.request.Request("https://api.vercel.com/v2/files",data=data[m["sha"]],method="POST",
          headers={**H,"x-vercel-digest":m["sha"],"Content-Type":"application/octet-stream"}); urllib.request.urlopen(r).read()
    body={"name":"jav-report","project":"jav-report","target":"production","files":man,
          "projectSettings":{"framework":None,"buildCommand":None,"outputDirectory":None,"installCommand":None}}
    r=urllib.request.Request("https://api.vercel.com/v13/deployments?skipAutoDetectionConfirmation=1",data=json.dumps(body).encode(),
          method="POST",headers={**H,"Content-Type":"application/json"}); print(json.load(urllib.request.urlopen(r)).get("url"))
def mark_uploaded():
    man=json.load(open(f"{OUT}/manifest.json")); json.dump(sorted({m["sha"] for m in man}),open(f"{OUT}/uploaded.json","w"))
if __name__=="__main__":
    if "--mark-uploaded" in sys.argv: mark_uploaded(); sys.exit()
    if "--no-scrape" not in sys.argv: subprocess.run([sys.executable,os.path.join(ROOT,"scrape.py")],check=True)
    man,files=bundle()
    if os.environ.get("VERCEL_TOKEN"): rest_deploy(man,files,os.environ["VERCEL_TOKEN"]); mark_uploaded()
    else: print("No VERCEL_TOKEN: deploy via MCP per docstring, then run: python3 deploy.py --mark-uploaded")
